/// A durable store of conversations and their messages.
///
/// The API is synchronous and main-actor bound, matching how SwiftData's main
/// context is used today. A future synced or self-hosted backend is expected
/// to be a local cache plus replication (for example an outbox of
/// `MessageChangeSet`s), not a blocking network store.
///
/// Every mutating call is one transaction: on failure nothing is written and
/// the error is rethrown. `changes` publishes only after a successful save.
///
/// A store also keeps each conversation's context checkpoints
/// (`ContextCheckpointStore`). `saveCheckpoint` rejects a checkpoint whose
/// covered message is not a stored top-level message; deleting that message
/// moves the checkpoint back to the closest earlier message (or removes it);
/// deleting a conversation deletes its checkpoints.
@MainActor
public protocol ChatHistoryStorage: ContextCheckpointStore {
    func conversations(matching query: ConversationQuery) throws -> [ConversationRecord]
    func conversation(id: UUID) throws -> ConversationRecord?
    @discardableResult func createConversation(_ draft: ConversationDraft) throws -> ConversationRecord
    @discardableResult func updateConversation(id: UUID, _ patch: ConversationPatch) throws -> ConversationRecord
    /// Deletes conversations and all of their messages. Unknown IDs are ignored.
    func deleteConversations(ids: Set<UUID>) throws
    func loadMessages(conversationID: UUID, window: MessageWindow) throws -> [Message]
    /// Applies one batch of upserts and deletions, then refreshes the
    /// conversation's summary fields and automatic title.
    func applyMessageChanges(_ changes: MessageChangeSet, conversationID: UUID) throws
    /// Creates a conversation with its full history in one transaction,
    /// preserving message IDs and the draft's timestamps. Used by importers.
    @discardableResult func importConversation(_ draft: ConversationDraft, messages: [Message]) throws -> ConversationRecord
    /// A conversation's checkpoints, oldest first.
    func checkpoints(conversationID: UUID) throws -> [ContextCheckpoint]
    var changes: AnyPublisher<ChatHistoryChange, Never> { get }
}

public extension ChatHistoryStorage {
    func loadMessages(conversationID: UUID) throws -> [Message] {
        try loadMessages(conversationID: conversationID, window: .all)
    }

    func containsConversation(id: UUID) throws -> Bool {
        try conversation(id: id) != nil
    }
}

/// Where a SwiftData-backed store keeps its file.
public enum ChatHistoryStoreLocation: Equatable, Sendable {
    case file(URL)
    case inMemory

    /// `Application Support/<directory>/<fileName>`.
    public static func applicationSupport(
        directory: String,
        fileName: String = "ChatHistory.store"
    ) -> ChatHistoryStoreLocation {
        .file(
            URL.applicationSupportDirectory
                .appending(path: directory, directoryHint: .isDirectory)
                .appending(path: fileName, directoryHint: .notDirectory)
        )
    }
}

// MARK: - Shared record rules

/// Record rules shared by every backend so they behave identically.
enum ConversationRecordRules {
    static func record(from draft: ConversationDraft, now: Date) -> ConversationRecord {
        let createdAt = draft.createdAt ?? now
        return ConversationRecord(
            id: draft.id,
            title: draft.title ?? ConversationDraft.defaultTitle,
            isTitleAutoGenerated: draft.title == nil,
            createdAt: createdAt,
            updatedAt: draft.updatedAt ?? createdAt,
            owner: draft.owner,
            threadKind: draft.threadKind,
            isPinned: draft.isPinned,
            isRetentionExempt: draft.isRetentionExempt,
            settings: draft.settings,
            metadata: draft.metadata
        )
    }

    static func apply(_ patch: ConversationPatch, to record: inout ConversationRecord, now: Date) {
        if let title = patch.title {
            record.title = title
            record.isTitleAutoGenerated = false
        }
        if let owner = patch.owner { record.owner = owner }
        if let threadKind = patch.threadKind { record.threadKind = threadKind }
        if let isPinned = patch.isPinned { record.isPinned = isPinned }
        if let isRetentionExempt = patch.isRetentionExempt { record.isRetentionExempt = isRetentionExempt }
        if let archivedAt = patch.archivedAt { record.archivedAt = archivedAt }
        if let settings = patch.settings { record.settings = settings }
        if let metadata = patch.metadata { record.metadata = metadata }
        if patch.bumpsUpdatedAt { record.updatedAt = now }
    }

    static func apply(
        _ summary: ConversationSummary,
        titleGenerator: any ConversationTitleGenerating,
        to record: inout ConversationRecord,
        updatedAt: Date
    ) {
        record.messageCount = summary.messageCount
        record.lastMessageAt = summary.lastMessageAt
        record.lastMessagePreview = summary.lastMessagePreview
        if record.isTitleAutoGenerated {
            record.title = summary.firstUserText.flatMap(titleGenerator.title(forFirstUserMessage:))
                ?? ConversationDraft.defaultTitle
        }
        record.updatedAt = updatedAt
    }

    /// Applies an import's messages to a fresh record: rows get sequential
    /// sort orders and `updatedAt` reflects the imported history, not now.
    static func importRows(
        for messages: [Message],
        draft: ConversationDraft,
        record: inout ConversationRecord,
        titleGenerator: any ConversationTitleGenerating
    ) throws -> (rows: [MessageRow], nextSortOrder: Int64) {
        var rows: [MessageRow] = []
        var next: Int64 = 0
        for message in messages {
            for var row in try MessageRowCodec.rows(for: message, parentID: message.parent?.uuid) {
                row.sortOrder = next
                next += 1
                rows.append(row)
            }
        }
        let summary = MessageChangePlanner.summary(of: rows)
        apply(
            summary,
            titleGenerator: titleGenerator,
            to: &record,
            updatedAt: draft.updatedAt ?? summary.lastMessageAt ?? record.createdAt
        )
        return (rows, next)
    }

    /// Conversations matching `query`, newest first, given a precomputed set
    /// of conversations whose messages match the text filter.
    static func filter(
        _ records: [ConversationRecord],
        query: ConversationQuery,
        messageTextMatches: Set<UUID>
    ) -> [ConversationRecord] {
        var result = records
            .filter(query.matches)
            .filter { record in
                guard let text = query.normalizedText else { return true }
                return record.title.localizedStandardContains(text) || messageTextMatches.contains(record.id)
            }
            .sorted { lhs, rhs in
                if lhs.updatedAt != rhs.updatedAt { return lhs.updatedAt > rhs.updatedAt }
                return lhs.id.uuidString < rhs.id.uuidString
            }
        if let limit = query.limit, limit >= 0, result.count > limit {
            result = Array(result.prefix(limit))
        }
        return result
    }
}
