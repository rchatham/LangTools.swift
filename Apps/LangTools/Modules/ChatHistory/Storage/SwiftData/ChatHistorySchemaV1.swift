//
//  ChatHistorySchemaV1.swift
//  ChatHistory
//
//  SwiftData schema, version 1. Frozen: never edit these models. Version 2
//  (ChatHistorySchemaV2.swift) reuses them unchanged and adds checkpoints.
//
//  Model rules (they keep a future CloudKit or sync backend possible):
//  no `@Attribute(.unique)`, every property has a default, no relationships.
//  Uniqueness is enforced by fetch-then-insert in the store, and messages
//  reference their conversation and parent by scalar IDs.
//
//  Entity names are deliberately distinct from Botsworth's legacy
//  `Conversation` / `PersistedMessage` entities.
//

import Foundation
import SwiftData

enum ChatHistorySchemaV1: VersionedSchema {
    static var versionIdentifier: Schema.Version { Schema.Version(1, 0, 0) }

    static var models: [any PersistentModel.Type] {
        [ChatHistoryConversation.self, ChatHistoryMessage.self]
    }

    @Model
    final class ChatHistoryConversation {
        var id: UUID = UUID()
        var title: String = ConversationDraft.defaultTitle
        var isTitleAutoGenerated: Bool = true
        var createdAt: Date = Date()
        var updatedAt: Date = Date()
        var lastMessageAt: Date?
        var lastMessagePreview: String?
        var messageCount: Int = 0
        var nextSortOrder: Int64 = 0
        var ownerKind: String?
        var ownerID: String?
        var threadKind: String?
        var isPinned: Bool = false
        var isRetentionExempt: Bool = false
        var archivedAt: Date?
        /// JSON `ConversationSettingsOverrides`; `nil` when empty.
        var settingsData: Data?
        /// JSON `[String: String]`; `nil` when empty.
        var metadataData: Data?

        init(id: UUID) {
            self.id = id
        }
    }

    @Model
    final class ChatHistoryMessage {
        var id: UUID = UUID()
        var conversationID: UUID = UUID()
        var parentID: UUID?
        var sortOrder: Int64 = 0
        var createdAt: Date = Date()
        var role: String = ""
        var contentKind: String = "string"
        var plainText: String = ""
        var payload: Data = Data()
        var payloadVersion: Int = 1

        init(id: UUID, conversationID: UUID) {
            self.id = id
            self.conversationID = conversationID
        }
    }
}

typealias ChatHistoryConversation = ChatHistorySchemaV1.ChatHistoryConversation
typealias ChatHistoryMessage = ChatHistorySchemaV1.ChatHistoryMessage

// MARK: - Record mapping

extension ChatHistoryConversation {
    var record: ConversationRecord {
        ConversationRecord(
            id: id,
            title: title,
            isTitleAutoGenerated: isTitleAutoGenerated,
            createdAt: createdAt,
            updatedAt: updatedAt,
            lastMessageAt: lastMessageAt,
            lastMessagePreview: lastMessagePreview,
            messageCount: messageCount,
            owner: ownerKind.flatMap { kind in ownerID.map { ConversationOwner(kind: kind, id: $0) } },
            threadKind: threadKind,
            isPinned: isPinned,
            isRetentionExempt: isRetentionExempt,
            archivedAt: archivedAt,
            settings: settingsData.flatMap { try? JSONDecoder().decode(ConversationSettingsOverrides.self, from: $0) } ?? .none,
            metadata: metadataData.flatMap { try? JSONDecoder().decode([String: String].self, from: $0) } ?? [:]
        )
    }

    func apply(_ record: ConversationRecord) {
        title = record.title
        isTitleAutoGenerated = record.isTitleAutoGenerated
        createdAt = record.createdAt
        updatedAt = record.updatedAt
        lastMessageAt = record.lastMessageAt
        lastMessagePreview = record.lastMessagePreview
        messageCount = record.messageCount
        ownerKind = record.owner?.kind
        ownerID = record.owner?.id
        threadKind = record.threadKind
        isPinned = record.isPinned
        isRetentionExempt = record.isRetentionExempt
        archivedAt = record.archivedAt
        settingsData = record.settings.isEmpty ? nil : try? JSONEncoder().encode(record.settings)
        metadataData = record.metadata.isEmpty ? nil : try? JSONEncoder().encode(record.metadata)
    }
}

extension ChatHistoryMessage {
    var row: MessageRow {
        MessageRow(
            id: id,
            parentID: parentID,
            sortOrder: sortOrder,
            createdAt: createdAt,
            role: role,
            contentKind: contentKind,
            plainText: plainText,
            payload: payload,
            payloadVersion: payloadVersion
        )
    }

    var key: MessageRowKey {
        MessageRowKey(id: id, parentID: parentID, sortOrder: sortOrder, createdAt: createdAt, contentKind: contentKind)
    }

    func apply(_ row: MessageRow) {
        parentID = row.parentID
        sortOrder = row.sortOrder
        createdAt = row.createdAt
        role = row.role
        contentKind = row.contentKind
        plainText = row.plainText
        payload = row.payload
        payloadVersion = row.payloadVersion
    }
}
