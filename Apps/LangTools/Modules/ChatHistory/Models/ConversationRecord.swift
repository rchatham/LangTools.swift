//  ChatHistory
//
//  Value types describing stored conversations. They are independent of the
//  storage backend so a host can swap SwiftData for an in-memory, synced or
//  self-hosted store without touching UI or session code.
//

import Foundation

/// Identifies who a conversation belongs to, without ChatHistory knowing what
/// that owner is. Botsworth uses `kind: "botsworth.bot"` and the bot's UUID.
public struct ConversationOwner: Hashable, Codable, Sendable {
    public var kind: String
    public var id: String

    public init(kind: String, id: String) {
        self.kind = kind
        self.id = id
    }
}

/// Per-conversation settings that override the host's global chat settings.
/// Every field is optional; `nil` means "inherit".
public struct ConversationSettingsOverrides: Codable, Hashable, Sendable {
    public var modelIdentifier: String?
    public var systemPrompt: String?
    public var maxContextMessages: Int?
    public var contextWindowPercent: Int?

    public static let none = ConversationSettingsOverrides()

    public init(
        modelIdentifier: String? = nil,
        systemPrompt: String? = nil,
        maxContextMessages: Int? = nil,
        contextWindowPercent: Int? = nil
    ) {
        self.modelIdentifier = modelIdentifier
        self.systemPrompt = systemPrompt
        self.maxContextMessages = maxContextMessages
        self.contextWindowPercent = contextWindowPercent
    }

    public var isEmpty: Bool { self == .none }
}

/// A snapshot of one stored conversation. Summary fields (`messageCount`,
/// `lastMessagePreview`, `lastMessageAt`) are maintained by the store so lists
/// can render without loading messages.
public struct ConversationRecord: Identifiable, Hashable, Sendable {
    public let id: UUID
    public var title: String
    public var isTitleAutoGenerated: Bool
    public var createdAt: Date
    /// Last time the title, settings or messages changed. Lists sort by this.
    public var updatedAt: Date
    public var lastMessageAt: Date?
    public var lastMessagePreview: String?
    /// Number of top-level messages (agent-event children are not counted).
    public var messageCount: Int
    public var owner: ConversationOwner?
    /// Host-defined thread category, for example `"main"` or `"topic"`.
    public var threadKind: String?
    public var isPinned: Bool
    /// When true, retention never deletes this conversation.
    public var isRetentionExempt: Bool
    public var archivedAt: Date?
    public var settings: ConversationSettingsOverrides
    public var metadata: [String: String]

    public var isArchived: Bool { archivedAt != nil }

    public init(
        id: UUID,
        title: String,
        isTitleAutoGenerated: Bool,
        createdAt: Date,
        updatedAt: Date,
        lastMessageAt: Date? = nil,
        lastMessagePreview: String? = nil,
        messageCount: Int = 0,
        owner: ConversationOwner? = nil,
        threadKind: String? = nil,
        isPinned: Bool = false,
        isRetentionExempt: Bool = false,
        archivedAt: Date? = nil,
        settings: ConversationSettingsOverrides = .none,
        metadata: [String: String] = [:]
    ) {
        self.id = id
        self.title = title
        self.isTitleAutoGenerated = isTitleAutoGenerated
        self.createdAt = createdAt
        self.updatedAt = updatedAt
        self.lastMessageAt = lastMessageAt
        self.lastMessagePreview = lastMessagePreview
        self.messageCount = messageCount
        self.owner = owner
        self.threadKind = threadKind
        self.isPinned = isPinned
        self.isRetentionExempt = isRetentionExempt
        self.archivedAt = archivedAt
        self.settings = settings
        self.metadata = metadata
    }
}

/// The fields needed to create a conversation. A `nil` title means the store
/// generates one from the first user message.
public struct ConversationDraft: Sendable {
    public static let defaultTitle = "New Conversation"

    public var id: UUID
    public var title: String?
    public var owner: ConversationOwner?
    public var threadKind: String?
    public var isPinned: Bool
    public var isRetentionExempt: Bool
    public var settings: ConversationSettingsOverrides
    public var metadata: [String: String]
    /// Set by importers to preserve original timestamps; `nil` means now.
    public var createdAt: Date?
    public var updatedAt: Date?

    public init(
        id: UUID = UUID(),
        title: String? = nil,
        owner: ConversationOwner? = nil,
        threadKind: String? = nil,
        isPinned: Bool = false,
        isRetentionExempt: Bool = false,
        settings: ConversationSettingsOverrides = .none,
        metadata: [String: String] = [:],
        createdAt: Date? = nil,
        updatedAt: Date? = nil
    ) {
        self.id = id
        self.title = title
        self.owner = owner
        self.threadKind = threadKind
        self.isPinned = isPinned
        self.isRetentionExempt = isRetentionExempt
        self.settings = settings
        self.metadata = metadata
        self.createdAt = createdAt
        self.updatedAt = updatedAt
    }
}

/// A partial update. `nil` leaves a field unchanged; the double optionals use
/// `.some(nil)` to clear a value.
public struct ConversationPatch: Sendable {
    /// Setting a title also turns off automatic titling.
    public var title: String?
    public var owner: ConversationOwner??
    public var threadKind: String??
    public var isPinned: Bool?
    public var isRetentionExempt: Bool?
    public var archivedAt: Date??
    public var settings: ConversationSettingsOverrides?
    public var metadata: [String: String]?

    public init(
        title: String? = nil,
        owner: ConversationOwner?? = nil,
        threadKind: String?? = nil,
        isPinned: Bool? = nil,
        isRetentionExempt: Bool? = nil,
        archivedAt: Date?? = nil,
        settings: ConversationSettingsOverrides? = nil,
        metadata: [String: String]? = nil
    ) {
        self.title = title
        self.owner = owner
        self.threadKind = threadKind
        self.isPinned = isPinned
        self.isRetentionExempt = isRetentionExempt
        self.archivedAt = archivedAt
        self.settings = settings
        self.metadata = metadata
    }

    /// Title, settings and metadata edits count as activity; pinning, archiving and
    /// ownership changes do not reorder lists.
    var bumpsUpdatedAt: Bool { title != nil || settings != nil || metadata != nil }

    public static func rename(_ title: String) -> ConversationPatch { .init(title: title) }
    public static func pin(_ isPinned: Bool) -> ConversationPatch { .init(isPinned: isPinned) }
    public static func archive(at date: Date?) -> ConversationPatch { .init(archivedAt: .some(date)) }
}

/// Which conversations to list. Results are ordered newest `updatedAt` first.
public struct ConversationQuery: Equatable, Sendable {
    public enum OwnerFilter: Equatable, Sendable {
        case any
        case unowned
        case owner(ConversationOwner)
        case ownerKind(String)
    }

    public var owner: OwnerFilter
    /// `nil` matches every thread kind, including conversations without one.
    public var threadKinds: Set<String>?
    public var includeArchived: Bool
    /// Case- and diacritic-insensitive match against titles and message text.
    public var text: String?
    public var limit: Int?

    public static let all = ConversationQuery()

    public init(
        owner: OwnerFilter = .any,
        threadKinds: Set<String>? = nil,
        includeArchived: Bool = false,
        text: String? = nil,
        limit: Int? = nil
    ) {
        self.owner = owner
        self.threadKinds = threadKinds
        self.includeArchived = includeArchived
        self.text = text
        self.limit = limit
    }

    func matches(_ record: ConversationRecord) -> Bool {
        if !includeArchived && record.isArchived { return false }
        switch owner {
        case .any: break
        case .unowned: if record.owner != nil { return false }
        case .owner(let owner): if record.owner != owner { return false }
        case .ownerKind(let kind): if record.owner?.kind != kind { return false }
        }
        if let threadKinds {
            guard let kind = record.threadKind, threadKinds.contains(kind) else { return false }
        }
        return true
    }

    var normalizedText: String? {
        guard let text = text?.trimmingCharacters(in: .whitespacesAndNewlines), !text.isEmpty else { return nil }
        return text
    }
}

/// Which messages to load. Every window counts top-level messages and
/// includes their agent-event children. Stores read only the selected
/// messages' payloads.
public enum MessageWindow: Equatable, Sendable {
    case all
    /// The newest `n` top-level messages.
    case latest(Int)
    /// `messageID` and every top-level message after it, extended back to at
    /// least the newest `minimumCount`. Sessions open long conversations
    /// this way from their latest checkpoint. If `messageID` is not stored,
    /// every message.
    case since(UUID, minimumCount: Int)
    /// Up to `limit` top-level messages immediately before `messageID`, for
    /// "load earlier". Empty when `messageID` is not stored.
    case before(UUID, limit: Int)
}

/// Notifications published by a store after a successful save.
public enum ChatHistoryChange: Equatable, Sendable {
    case conversationUpserted(UUID)
    case conversationsDeleted(Set<UUID>)
    case messagesChanged(UUID)
}

public enum ChatHistoryError: LocalizedError, Equatable {
    case conversationNotFound(UUID)
    case conversationAlreadyExists(UUID)
    case storeUnavailable(String)
    /// A checkpoint must cover a stored top-level message of its conversation.
    case messageNotFound(UUID)

    public var errorDescription: String? {
        switch self {
        case .conversationNotFound:
            return "The conversation is no longer available."
        case .conversationAlreadyExists:
            return "A conversation with this identifier already exists."
        case .storeUnavailable(let reason):
            return "Chat history is unavailable: \(reason)"
        case .messageNotFound:
            return "The message is no longer available."
        }
    }
}
