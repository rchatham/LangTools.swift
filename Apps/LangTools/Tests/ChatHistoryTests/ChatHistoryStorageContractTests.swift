/// Behavior every `ChatHistoryStorage` must share. Subclasses supply the
/// backend; the base class itself is skipped.
@MainActor
class ChatHistoryStorageContractTests: XCTestCase {
    var clock = Date(timeIntervalSinceReferenceDate: 1_000_000)

    func makeStorage() throws -> any ChatHistoryStorage {
        throw XCTSkip("Abstract contract suite")
    }

    /// Fails the next save when supported by the backend.
    func failNextSave(_ storage: any ChatHistoryStorage) {
        var failed = false
        let hook: () throws -> Void = {
            if !failed { failed = true; throw ScriptedError.saveFailed }
        }
        if let storage = storage as? SwiftDataChatHistoryStorage { storage.saveHook = hook }
        if let storage = storage as? InMemoryChatHistoryStorage { storage.saveHook = hook }
    }

    func advance(_ seconds: TimeInterval = 1) { clock = clock.addingTimeInterval(seconds) }

    // MARK: Conversations

    func testCreateGetAndRejectDuplicateIDs() throws {
        let storage = try makeStorage()
        let owner = ConversationOwner(kind: "bot", id: "primary")
        let created = try storage.createConversation(
            ConversationDraft(owner: owner, threadKind: "topic", settings: .init(systemPrompt: "custom"), metadata: ["k": "v"])
        )

        let fetched = try XCTUnwrap(try storage.conversation(id: created.id))
        XCTAssertEqual(fetched, created)
        XCTAssertEqual(fetched.title, ConversationDraft.defaultTitle)
        XCTAssertTrue(fetched.isTitleAutoGenerated)
        XCTAssertEqual(fetched.owner, owner)
        XCTAssertEqual(fetched.settings.systemPrompt, "custom")
        XCTAssertEqual(fetched.metadata, ["k": "v"])
        XCTAssertThrowsError(try storage.createConversation(ConversationDraft(id: created.id))) { error in
            XCTAssertEqual(error as? ChatHistoryError, .conversationAlreadyExists(created.id))
        }
    }

    func testPatchesRenameDisablesAutoTitleAndOnlyContentChangesReorder() throws {
        let storage = try makeStorage()
        let record = try storage.createConversation(ConversationDraft())
        let createdAt = record.updatedAt
        advance()

        let pinned = try storage.updateConversation(id: record.id, .pin(true))
        XCTAssertTrue(pinned.isPinned)
        XCTAssertEqual(pinned.updatedAt, createdAt, "Pinning must not reorder lists")

        let renamed = try storage.updateConversation(id: record.id, .rename("Named"))
        XCTAssertEqual(renamed.title, "Named")
        XCTAssertFalse(renamed.isTitleAutoGenerated)
        XCTAssertEqual(renamed.updatedAt, clock)

        let cleared = try storage.updateConversation(id: record.id, ConversationPatch(owner: .some(nil), archivedAt: .some(clock)))
        XCTAssertNil(cleared.owner)
        XCTAssertTrue(cleared.isArchived)

        XCTAssertThrowsError(try storage.updateConversation(id: UUID(), .pin(true)))
    }

    func testQueriesFilterByOwnerThreadKindArchiveAndText() throws {
        let storage = try makeStorage()
        let bot = ConversationOwner(kind: "bot", id: "1")
        let main = try storage.createConversation(ConversationDraft(title: "Main", owner: bot, threadKind: "main"))
        advance()
        let topic = try storage.createConversation(ConversationDraft(title: "Recipes", owner: bot, threadKind: "topic"))
        advance()
        let plain = try storage.createConversation(ConversationDraft(title: "Plain"))
        advance()
        let archived = try storage.createConversation(ConversationDraft(title: "Old", owner: bot, threadKind: "topic"))
        try storage.updateConversation(id: archived.id, .archive(at: clock))
        try storage.applyMessageChanges(MessageChangeSet(upserts: [text("Find the café menu", .user, at: 1)]), conversationID: main.id)

        XCTAssertEqual(try storage.conversations(matching: .all).map(\.id), [main.id, plain.id, topic.id],
                       "Newest updatedAt first; archived hidden by default")
        XCTAssertEqual(try storage.conversations(matching: .init(owner: .unowned)).map(\.id), [plain.id])
        XCTAssertEqual(Set(try storage.conversations(matching: .init(owner: .owner(bot), includeArchived: true)).map(\.id)),
                       [main.id, topic.id, archived.id])
        XCTAssertEqual(try storage.conversations(matching: .init(owner: .ownerKind("bot"), threadKinds: ["topic"])).map(\.id), [topic.id])
        XCTAssertEqual(try storage.conversations(matching: .init(text: "recipes")).map(\.id), [topic.id], "Title match")
        XCTAssertEqual(try storage.conversations(matching: .init(text: "CAFE")).map(\.id), [main.id],
                       "Message match is case- and diacritic-insensitive")
        XCTAssertEqual(try storage.conversations(matching: .init(limit: 1)).count, 1)
    }

    func testDeleteConversationsRemovesMessagesAndPublishes() throws {
        let storage = try makeStorage()
        let record = try storage.createConversation(ConversationDraft())
        try storage.applyMessageChanges(MessageChangeSet(upserts: [text("hi", .user, at: 1)]), conversationID: record.id)
        var changes: [ChatHistoryChange] = []
        let subscription = storage.changes.sink { changes.append($0) }

        try storage.deleteConversations(ids: [record.id, UUID()])

        XCTAssertNil(try storage.conversation(id: record.id))
        XCTAssertThrowsError(try storage.loadMessages(conversationID: record.id))
        XCTAssertEqual(changes, [.conversationsDeleted([record.id])])
        subscription.cancel()
    }

    // MARK: Messages

    func testUpsertsKeepOrderAndRefreshSummaryAndAutoTitle() throws {
        let storage = try makeStorage()
        let record = try storage.createConversation(ConversationDraft())
        let prompt = text("What is the weather in Paris today?\nThanks", .user, at: 1)
        let reply = text("Sunny", .assistant, at: 2)
        advance()

        try storage.applyMessageChanges(MessageChangeSet(upserts: [prompt, reply]), conversationID: record.id)
        reply.contentType = .string("Sunny and 22°C")
        try storage.applyMessageChanges(MessageChangeSet(upserts: [reply]), conversationID: record.id)

        let loaded = try storage.loadMessages(conversationID: record.id)
        XCTAssertEqual(loaded.map(\.uuid), [prompt.uuid, reply.uuid])
        XCTAssertEqual(loaded.last?.text, "Sunny and 22°C")
        let updated = try XCTUnwrap(try storage.conversation(id: record.id))
        XCTAssertEqual(updated.title, "What is the weather in Paris today?...")
        XCTAssertEqual(updated.messageCount, 2)
        XCTAssertEqual(updated.lastMessagePreview, "Sunny and 22°C")
        XCTAssertEqual(updated.lastMessageAt, reply.createdAt)
        XCTAssertEqual(updated.updatedAt, clock)
    }

    func testIdenticalUpsertsDoNotTouchTheConversation() throws {
        let storage = try makeStorage()
        let record = try storage.createConversation(ConversationDraft())
        let message = text("same", .user, at: 1)
        try storage.applyMessageChanges(MessageChangeSet(upserts: [message]), conversationID: record.id)
        let before = try XCTUnwrap(try storage.conversation(id: record.id))
        advance()
        var changes: [ChatHistoryChange] = []
        let subscription = storage.changes.sink { changes.append($0) }

        try storage.applyMessageChanges(MessageChangeSet(upserts: [message]), conversationID: record.id)

        XCTAssertEqual(try storage.conversation(id: record.id)?.updatedAt, before.updatedAt)
        XCTAssertTrue(changes.isEmpty)
        subscription.cancel()
    }

    func testDeletionsRemoveDescendantsAndChildrenAttachWhenTheirParentArrives() throws {
        let storage = try makeStorage()
        let record = try storage.createConversation(ConversationDraft())
        let parent = Message(
            role: .system,
            contentType: .agentEvent(AgentEventContent(type: .started, agentName: "A", details: "root")),
            createdAt: Date(timeIntervalSinceReferenceDate: 0)
        )
        let child = Message(
            role: .system,
            contentType: .agentEvent(AgentEventContent(type: .toolCalled, agentName: "A", details: "child", parent: parent)),
            createdAt: Date(timeIntervalSinceReferenceDate: 1)
        )
        parent.contentType = .agentEvent(AgentEventContent(type: .started, agentName: "A", details: "root", children: [child]))
        let keep = text("keep", .user, at: 5)

        // A child saved before its parent is shown flat...
        try storage.applyMessageChanges(MessageChangeSet(upserts: [child, keep]), conversationID: record.id)
        var loaded = try storage.loadMessages(conversationID: record.id)
        XCTAssertEqual(loaded.map(\.uuid), [child.uuid, keep.uuid])

        // ...and nests once the parent exists.
        try storage.applyMessageChanges(MessageChangeSet(upserts: [parent]), conversationID: record.id)
        loaded = try storage.loadMessages(conversationID: record.id)
        XCTAssertEqual(loaded.map(\.uuid), [parent.uuid, keep.uuid])
        XCTAssertEqual(loaded.first?.childMessages.map(\.uuid), [child.uuid])

        try storage.applyMessageChanges(MessageChangeSet(deletions: [parent.uuid]), conversationID: record.id)
        loaded = try storage.loadMessages(conversationID: record.id)
        XCTAssertEqual(loaded.map(\.uuid), [keep.uuid], "Deleting a parent deletes its children")
        XCTAssertEqual(try storage.conversation(id: record.id)?.messageCount, 1)
    }

    func testFailedSaveLeavesEverythingUnchanged() throws {
        let storage = try makeStorage()
        let record = try storage.createConversation(ConversationDraft())
        let first = text("first", .user, at: 1)
        try storage.applyMessageChanges(MessageChangeSet(upserts: [first]), conversationID: record.id)
        let before = try XCTUnwrap(try storage.conversation(id: record.id))
        advance()

        failNextSave(storage)
        XCTAssertThrowsError(try storage.applyMessageChanges(
            MessageChangeSet(upserts: [text("second", .assistant, at: 2)], deletions: [first.uuid]),
            conversationID: record.id
        ))

        XCTAssertEqual(try storage.loadMessages(conversationID: record.id).map(\.uuid), [first.uuid])
        XCTAssertEqual(try storage.conversation(id: record.id), before)
        // The next batch still works and does not resurrect the failed one.
        try storage.applyMessageChanges(MessageChangeSet(upserts: [text("third", .assistant, at: 3)]), conversationID: record.id)
        XCTAssertEqual(try storage.loadMessages(conversationID: record.id).map(\.text), ["first", "third"])
    }

    func testImportPreservesIdentityDatesAndOrder() throws {
        let storage = try makeStorage()
        let created = Date(timeIntervalSinceReferenceDate: 100)
        let draft = ConversationDraft(title: "Imported", threadKind: "topic", createdAt: created)
        let messages = [text("q", .user, at: 200), text("a", .assistant, at: 300)]

        let record = try storage.importConversation(draft, messages: messages)

        XCTAssertEqual(record.id, draft.id)
        XCTAssertEqual(record.createdAt, created)
        XCTAssertEqual(record.updatedAt, Date(timeIntervalSinceReferenceDate: 300), "Imports age from their history, not now")
        XCTAssertFalse(record.isTitleAutoGenerated)
        XCTAssertEqual(try storage.loadMessages(conversationID: record.id), messages)
        XCTAssertThrowsError(try storage.importConversation(draft, messages: []))
    }

    func testLatestWindowReturnsNewestTopLevelMessages() throws {
        let storage = try makeStorage()
        let record = try storage.createConversation(ConversationDraft())
        let messages = (0..<5).map { text("m\($0)", .user, at: TimeInterval($0)) }
        try storage.applyMessageChanges(MessageChangeSet(upserts: messages), conversationID: record.id)

        XCTAssertEqual(try storage.loadMessages(conversationID: record.id, window: .latest(2)).map(\.text), ["m3", "m4"])
    }

    // MARK: Windows

    /// Five plain messages, then an agent event with two children, then five more.
    private func windowedConversation(_ storage: any ChatHistoryStorage) throws -> (UUID, [Message]) {
        let record = try storage.createConversation(ConversationDraft())
        var messages = (0..<5).map { text("m\($0)", .user, at: TimeInterval($0)) }
        let childA = Message(role: .system, contentType: .agentEvent(AgentEventContent(type: .toolCalled, agentName: "A", details: "a")),
                             createdAt: Date(timeIntervalSinceReferenceDate: 5.1))
        let childB = Message(role: .system, contentType: .agentEvent(AgentEventContent(type: .completed, agentName: "A", details: "b")),
                             createdAt: Date(timeIntervalSinceReferenceDate: 5.2))
        messages.append(Message(role: .system,
                                contentType: .agentEvent(AgentEventContent(type: .started, agentName: "A", details: "root", children: [childA, childB])),
                                createdAt: Date(timeIntervalSinceReferenceDate: 5)))
        messages += (6..<11).map { text("m\($0)", .assistant, at: TimeInterval($0)) }
        try storage.applyMessageChanges(MessageChangeSet(upserts: messages), conversationID: record.id)
        return (record.id, try storage.loadMessages(conversationID: record.id))
    }

    func testWindowsAreSlicesOfTheFullHistoryWithTheirChildren() throws {
        let storage = try makeStorage()
        let (id, all) = try windowedConversation(storage)
        XCTAssertEqual(all.count, 11)
        func ids(_ window: MessageWindow) throws -> [UUID] { try storage.loadMessages(conversationID: id, window: window).map(\.uuid) }

        XCTAssertEqual(try ids(.latest(3)), all.suffix(3).map(\.uuid))
        let latestSix = try storage.loadMessages(conversationID: id, window: .latest(6))
        XCTAssertEqual(latestSix.map(\.uuid), all.suffix(6).map(\.uuid))
        XCTAssertEqual(latestSix.first?.childMessages.count, 2, "An agent event comes with its children")
        XCTAssertEqual(try ids(.latest(50)), all.map(\.uuid))
        XCTAssertEqual(try ids(.latest(0)), [])

        XCTAssertEqual(try ids(.since(all[7].uuid, minimumCount: 2)), all.suffix(4).map(\.uuid), "From the message on")
        XCTAssertEqual(try ids(.since(all[9].uuid, minimumCount: 5)), all.suffix(5).map(\.uuid), "Extended to the minimum")
        XCTAssertEqual(try ids(.since(UUID(), minimumCount: 1)), all.map(\.uuid), "An unknown message loads everything")

        XCTAssertEqual(try ids(.before(all[7].uuid, limit: 3)), all[4..<7].map(\.uuid))
        XCTAssertEqual(try ids(.before(all[2].uuid, limit: 10)), all[0..<2].map(\.uuid))
        XCTAssertEqual(try ids(.before(UUID(), limit: 10)), [])
        let page = try storage.loadMessages(conversationID: id, window: .before(all[6].uuid, limit: 1))
        XCTAssertEqual(page.first?.childMessages.map(\.text), all[5].childMessages.map(\.text))
    }

    // MARK: Checkpoints

    private func checkpoint(_ conversationID: UUID, through messageID: UUID, _ summary: String, at seconds: TimeInterval) -> ContextCheckpoint {
        ContextCheckpoint(
            conversationID: conversationID,
            coversThroughMessageID: messageID,
            summary: summary,
            tokenEstimate: 4,
            model: "openai/gpt-4o-mini",
            createdAt: Date(timeIntervalSinceReferenceDate: seconds)
        )
    }

    func testCheckpointsAreSavedAndTheNewestIsLatest() throws {
        let storage = try makeStorage()
        let (id, all) = try windowedConversation(storage)
        XCTAssertNil(try storage.latestCheckpoint(conversationID: id))
        let older = checkpoint(id, through: all[3].uuid, "older", at: 10)
        let newer = checkpoint(id, through: all[8].uuid, "newer", at: 20)

        try storage.saveCheckpoint(newer)
        try storage.saveCheckpoint(older)

        XCTAssertEqual(try storage.latestCheckpoint(conversationID: id), newer)
        XCTAssertEqual(try storage.checkpoints(conversationID: id), [older, newer], "Oldest first")
        XCTAssertThrowsError(try storage.latestCheckpoint(conversationID: UUID()))
    }

    func testACheckpointMustCoverAStoredTopLevelMessage() throws {
        let storage = try makeStorage()
        let (id, all) = try windowedConversation(storage)
        let child = try XCTUnwrap(all[5].childMessages.first)

        for boundary in [UUID(), child.uuid] {
            XCTAssertThrowsError(try storage.saveCheckpoint(checkpoint(id, through: boundary, "bad", at: 1))) { error in
                XCTAssertEqual(error as? ChatHistoryError, .messageNotFound(boundary))
            }
        }
        let missing = UUID()
        XCTAssertThrowsError(try storage.saveCheckpoint(checkpoint(missing, through: all[0].uuid, "x", at: 1))) { error in
            XCTAssertEqual(error as? ChatHistoryError, .conversationNotFound(missing))
        }
        XCTAssertEqual(try storage.checkpoints(conversationID: id), [])
    }

    func testDeletingTheCoveredMessageMovesTheCheckpointBack() throws {
        let storage = try makeStorage()
        let (id, all) = try windowedConversation(storage)
        let saved = checkpoint(id, through: all[3].uuid, "summary", at: 10)
        try storage.saveCheckpoint(saved)

        try storage.applyMessageChanges(MessageChangeSet(deletions: [all[3].uuid]), conversationID: id)
        var moved = saved
        moved.coversThroughMessageID = all[2].uuid
        XCTAssertEqual(try storage.checkpoints(conversationID: id), [moved], "It still summarizes the deleted turn")

        try storage.applyMessageChanges(MessageChangeSet(deletions: [all[7].uuid]), conversationID: id)
        XCTAssertEqual(try storage.checkpoints(conversationID: id), [moved], "Deleting later messages changes nothing")

        try storage.applyMessageChanges(MessageChangeSet(deletions: Set(all[0...2].map(\.uuid))), conversationID: id)
        XCTAssertEqual(try storage.checkpoints(conversationID: id), [], "Nothing earlier remains, so the checkpoint goes")
    }

    func testAFailedSaveLeavesCheckpointsUnchanged() throws {
        let storage = try makeStorage()
        let (id, all) = try windowedConversation(storage)
        let saved = checkpoint(id, through: all[3].uuid, "summary", at: 10)
        try storage.saveCheckpoint(saved)

        failNextSave(storage)
        XCTAssertThrowsError(try storage.applyMessageChanges(MessageChangeSet(deletions: [all[3].uuid]), conversationID: id))
        XCTAssertEqual(try storage.checkpoints(conversationID: id), [saved])

        failNextSave(storage)
        XCTAssertThrowsError(try storage.saveCheckpoint(checkpoint(id, through: all[9].uuid, "lost", at: 20)))
        XCTAssertEqual(try storage.checkpoints(conversationID: id), [saved])
    }

    func testDeletingAConversationDeletesItsCheckpoints() throws {
        let storage = try makeStorage()
        let (id, all) = try windowedConversation(storage)
        try storage.saveCheckpoint(checkpoint(id, through: all[3].uuid, "summary", at: 10))

        try storage.deleteConversations(ids: [id])
        try storage.createConversation(ConversationDraft(id: id))

        XCTAssertEqual(try storage.checkpoints(conversationID: id), [])
    }

    func testMessageChangesForUnknownConversationThrow() throws {
        let storage = try makeStorage()
        let missing = UUID()
        XCTAssertThrowsError(try storage.applyMessageChanges(MessageChangeSet(upserts: [text("x", .user, at: 1)]), conversationID: missing)) { error in
            XCTAssertEqual(error as? ChatHistoryError, .conversationNotFound(missing))
        }
    }
}

@MainActor
final class SwiftDataFileStorageContractTests: ChatHistoryStorageContractTests {
    private var url: URL!

    override func makeStorage() throws -> any ChatHistoryStorage {
        url = temporaryStoreURL()
        return try SwiftDataChatHistoryStorage(location: .file(url), now: { [unowned self] in self.clock })
    }

    override func tearDown() async throws {
        if let url { try? FileManager.default.removeItem(at: url.deletingLastPathComponent()) }
        try await super.tearDown()
    }

    func testDataSurvivesReopeningTheStore() throws {
        let storage = try makeStorage()
        let record = try storage.createConversation(ConversationDraft(owner: .init(kind: "bot", id: "1"), threadKind: "main", isRetentionExempt: true))
        let messages = [text("persist me", .user, at: 1), text("ok", .assistant, at: 2)]
        try storage.applyMessageChanges(MessageChangeSet(upserts: messages), conversationID: record.id)
        let saved = try XCTUnwrap(try storage.conversation(id: record.id))

        let reopened = try SwiftDataChatHistoryStorage(location: .file(url))

        XCTAssertEqual(try reopened.conversation(id: record.id), saved)
        XCTAssertEqual(try reopened.loadMessages(conversationID: record.id), messages)
    }

    func testEqualTimestampsKeepInsertionOrderAcrossReopen() throws {
        let storage = try makeStorage()
        let record = try storage.createConversation(ConversationDraft())
        let first = text("first", .user, at: 7)
        let second = text("second", .assistant, at: 7)
        let childA = Message(role: .system, contentType: .agentEvent(AgentEventContent(type: .toolCalled, agentName: "A", details: "a")),
                             createdAt: Date(timeIntervalSinceReferenceDate: 8))
        let childB = Message(role: .system, contentType: .agentEvent(AgentEventContent(type: .completed, agentName: "A", details: "b")),
                             createdAt: Date(timeIntervalSinceReferenceDate: 8))
        let event = Message(role: .system,
                            contentType: .agentEvent(AgentEventContent(type: .started, agentName: "A", details: "root", children: [childA, childB])),
                            createdAt: Date(timeIntervalSinceReferenceDate: 8))
        try storage.applyMessageChanges(MessageChangeSet(upserts: [first, second]), conversationID: record.id)
        try storage.applyMessageChanges(MessageChangeSet(upserts: [event]), conversationID: record.id)
        // Re-saving an earlier message must not move it after later ones.
        try storage.applyMessageChanges(MessageChangeSet(upserts: [first]), conversationID: record.id)

        let reopened = try SwiftDataChatHistoryStorage(location: .file(url))
        let loaded = try reopened.loadMessages(conversationID: record.id)

        XCTAssertEqual(loaded.map(\.uuid), [first.uuid, second.uuid, event.uuid])
        XCTAssertEqual(loaded.last?.childMessages.map(\.uuid), [childA.uuid, childB.uuid])
        let latest = try reopened.loadMessages(conversationID: record.id, window: .latest(1))
        XCTAssertEqual(latest.first?.childMessages.map(\.uuid), [childA.uuid, childB.uuid],
                       "Equal timestamps keep their order in windowed loads too")
    }

    func testCheckpointsSurviveReopeningTheStore() throws {
        let storage = try makeStorage()
        let record = try storage.createConversation(ConversationDraft())
        let message = text("covered", .user, at: 1)
        try storage.applyMessageChanges(MessageChangeSet(upserts: [message]), conversationID: record.id)
        let saved = ContextCheckpoint(conversationID: record.id, coversThroughMessageID: message.uuid, summary: "s", tokenEstimate: 1, model: "m")
        try storage.saveCheckpoint(saved)

        let reopened = try SwiftDataChatHistoryStorage(location: .file(url))

        XCTAssertEqual(try reopened.checkpoints(conversationID: record.id), [saved])
    }

    /// A store written by schema version 1 opens with its data intact and
    /// gains checkpoints.
    func testAVersionOneStoreMigratesToVersionTwo() throws {
        url = temporaryStoreURL()
        let conversationID = UUID()
        let message = text("from version one", .user, at: 1)
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        do {
            let schema = Schema(versionedSchema: ChatHistorySchemaV1.self)
            let container = try ModelContainer(
                for: schema,
                configurations: [ModelConfiguration("ChatHistory", schema: schema, url: url, allowsSave: true, cloudKitDatabase: .none)]
            )
            let context = ModelContext(container)
            let conversation = ChatHistorySchemaV1.ChatHistoryConversation(id: conversationID)
            conversation.title = "Old"
            conversation.isTitleAutoGenerated = false
            conversation.messageCount = 1
            conversation.nextSortOrder = 1
            context.insert(conversation)
            let row = ChatHistorySchemaV1.ChatHistoryMessage(id: message.uuid, conversationID: conversationID)
            row.apply(try MessageRowCodec.row(for: message, parentID: nil))
            context.insert(row)
            try context.save()
        }

        let migrated = try SwiftDataChatHistoryStorage(location: .file(url))

        XCTAssertEqual(try migrated.conversation(id: conversationID)?.title, "Old")
        XCTAssertEqual(try migrated.loadMessages(conversationID: conversationID), [message])
        let saved = ContextCheckpoint(conversationID: conversationID, coversThroughMessageID: message.uuid, summary: "s", tokenEstimate: 1, model: "m")
        try migrated.saveCheckpoint(saved)
        XCTAssertEqual(try migrated.latestCheckpoint(conversationID: conversationID), saved)
    }
}

